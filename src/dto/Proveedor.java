package dto;

import java.util.Objects;

public class Proveedor {
    private int id;
    private String nombre;
    private String apellido;
    private String telefono;
    private byte[] imagen;
    private String empresa;
    private String correo;
    private String ciudad;
    private String colonia;
    private String codigoPostal;
    private String calle;
    private String numero;
    private String estado;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getApellido() {
        return apellido;
    }

    public void setApellido(String apellido) {
        this.apellido = apellido;
    }

    public String getTelefono() {
        return telefono;
    }

    public void setTelefono(String telefono) {
        this.telefono = telefono;
    }

    public byte[] getImagen() {
        return imagen;
    }

    public void setImagen(byte[] imagen) {
        this.imagen = imagen;
    }

    public String getEmpresa() {
        return empresa;
    }

    public void setEmpresa(String empresa) {
        this.empresa = empresa;
    }

    public String getCorreo() {
        return correo;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public String getCiudad() {
        return ciudad;
    }

    public void setCiudad(String ciudad) {
        this.ciudad = ciudad;
    }

    public String getColonia() {
        return colonia;
    }

    public void setColonia(String colonia) {
        this.colonia = colonia;
    }

    public String getCodigoPostal() {
        return codigoPostal;
    }

    public void setCodigoPostal(String codigoPostal) {
        this.codigoPostal = codigoPostal;
    }

    public String getCalle() {
        return calle;
    }

    public void setCalle(String calle) {
        this.calle = calle;
    }

    public String getNumero() {
        return numero;
    }

    public void setNumero(String numero) {
        this.numero = numero;
    }

    public String getEstado() {
        return estado;
    }

    public void setEstado(String estado) {
        this.estado = estado;
    }

    @Override
    public int hashCode() {
        int hash = 7;
        hash = 17 * hash + this.id;
        return hash;
    }

    @Override
    public boolean equals(Object obj) {
        if (this == obj) {
            return true;
        }
        if (obj == null) {
            return false;
        }
        if (getClass() != obj.getClass()) {
            return false;
        }
        final Proveedor other = (Proveedor) obj;
        return this.id == other.id;
    }

    @Override
    public String toString() {
        return "\nProveedor{" + "\nid=" + id + ", \nnombre=" + nombre + 
                ", \napellido=" + apellido + ", \ntelefono=" + telefono + 
                ", \nimagen=" + imagen + ", \nempresa=" + empresa + 
                ", \ncorreo=" + correo + ", \nciudad=" + ciudad + ", \ncolonia=" 
                + colonia + ", \ncodigoPostal=" + codigoPostal + ", \ncalle=" + 
                calle + ", \nnumero=" + numero + ", \nestado=" + estado + "}\n";
    }
    
    
    
}
